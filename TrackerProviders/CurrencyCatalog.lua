function addon.GetCurrencyCatalog(selected)
    local text = addon.panelText
    local rows = {
        {id = -1, name = text.money, icon = 133784, category = categoryNames[0]},
        {id = -2, name = text.crests, icon = 7639523, category = categoryNames[0]},
    }
    local seen = {[-1] = true, [-2] = true}
    local function Add(id, category)
        if not id or seen[id] then return end
        local info = C_CurrencyInfo.GetCurrencyInfo(id)
        if not info or not info.name or info.name == "" then return end
        seen[id] = true
        rows[#rows+1] = {id=id, name=info.name, icon=info.iconFileID, quantity=info.quantity or 0, category=category}
    end
    for _, entry in ipairs(addon.currencyRegistry) do Add(entry[1], categoryNames[entry[2]] or categoryNames[1]) end
    local category = categoryNames[1]
    for index=1,C_CurrencyInfo.GetCurrencyListSize() do
        local info = C_CurrencyInfo.GetCurrencyListInfo(index)
        if info and info.isHeader then category = info.name or categoryNames[1]
        elseif info then
            local link = C_CurrencyInfo.GetCurrencyListLink(index)
            Add(link and C_CurrencyInfo.GetCurrencyIDFromLink(link), category)
        end
    end
    for _,id in ipairs(selected or {}) do if id > 0 then Add(id, categoryNames[1]) end end
    table.sort(rows,function(a,b)
        if a.id < 0 or b.id < 0 then return a.id < 0 and (b.id >= 0 or a.id > b.id) end
        local x,y=addon.currencyCategoryOrder[a.category] or 100,addon.currencyCategoryOrder[b.category] or 100
        return x==y and (a.name==b.name and a.id<b.id or a.name<b.name) or x<y
    end)
    return rows
end
