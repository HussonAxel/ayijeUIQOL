"""Capture only panel settings and weekly memory; never modify FunelQOL saves.
Run from ayijeUIQOL with Python/lupa. The output is local and git-ignored.
"""
from pathlib import Path
import json
from lupa.lua51 import LuaRuntime

BASE = Path(__file__).resolve().parents[1]
lua = LuaRuntime()
read = lua.eval('function(s) local e={}; local f=assert(loadstring(s)); setfenv(f,e); f(); return e end')

def plain(value):
    if hasattr(value, 'items'):
        return {k: plain(v) for k, v in value.items()}
    return value

def literal(value):
    if isinstance(value, dict):
        return '{' + ','.join('[' + literal(k) + ']=' + literal(v) for k, v in sorted(value.items(), key=lambda p: str(p[0]))) + '}'
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if value is True: return 'true'
    if value is False: return 'false'
    if value is None: return 'nil'
    return repr(value)

snapshot = {'layouts': {}, 'characters': {}}
for path in (BASE.parents[2] / 'WTF' / 'Account').rglob('FunelQOL.lua'):
    env = read(path.read_text(encoding='utf-8-sig'))
    account, char = env['FunelQOLDB'], env['FunelQOLCharDB']
    for label, db in [('Account', account and account['panels']),
                      (path.parents[1].name + ' - ' + path.parents[2].name, char)]:
        if not db or not db['layouts']: continue
        for name, layout in db['layouts'].items():
            settings = plain(layout)
            ids = [k for k in settings if isinstance(k, str) and k.startswith('panel') and k[5:].isdigit()]
            count = db['panelCount'] or max([int(k[5:]) for k in ids] or [0])
            panels = {k: settings[k] for k in ids if int(k[5:]) <= count}
            if panels: snapshot['layouts'][label + ': ' + str(name)] = panels
    if char and char['weekly']:
        snapshot['characters'][path.parents[2].name + ':' + path.parents[1].name] = {'weekly': plain(char['weekly'])}

target = BASE / 'TrackerSavedPanels.lua'
target.write_text('-- Local recovery snapshot of user-owned settings; generated by tools/Import-FunelTrackers.py.\n'
                  'local _, ns = ...\nns.TrackerSavedPanels=' + literal(snapshot) + '\n', encoding='utf-8', newline='\n')
print('Saved', len(snapshot['layouts']), 'panel layouts and', len(snapshot['characters']), 'weekly memories to', target.name)
